/**
 * Builds a self-contained contact sheet for reviewing the generated artwork.
 *
 * The PNGs are inlined as data URIs rather than referenced by path, so the file
 * renders identically no matter which directory the preview server roots at.
 *
 * Run: npm run assets:preview
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = path.join(ROOT, 'assets');
const DEST = path.join(ROOT, 'tools', 'preview-assets.html');

const dataUri = (file) =>
  `data:image/png;base64,${fs.readFileSync(path.join(ASSETS, file)).toString('base64')}`;

const icon = dataUri('icon.png');
const adaptive = dataUri('adaptive-icon.png');
const splash = dataUri('splash-icon.png');
const favicon = dataUri('favicon.png');

// The adaptive foreground is 1024px with the mark in the centre 64%. The masks
// below scale it to the 108dp canvas and then crop, which is what an OEM
// launcher does — if the mark clips here, it clips on a real device.
const mask = (radius, zoom = 266 / 1024) => `
  <div style="width:180px;height:180px;overflow:hidden;${radius ? `border-radius:${radius};` : ''}background:#0D0D12">
    <img src="${adaptive}" style="position:absolute;width:${180 * zoom}px;height:${180 * zoom}px;left:50%;top:50%;transform:translate(-50%,-50%)">
  </div>`;

const html = `<!doctype html>
<html><head><meta charset="utf-8"><title>DEEPER asset check</title>
<style>
  body { margin:0; background:#17171f; color:#e8e8ef; padding:28px;
         font:14px ui-sans-serif,system-ui,-apple-system,sans-serif; }
  h1 { font-size:15px; font-weight:600; margin:0 0 22px; }
  h1 + h1 { margin-top:40px; }
  .row { display:flex; gap:26px; align-items:flex-end; flex-wrap:wrap; }
  figure { margin:0; text-align:center; }
  figcaption { margin-top:10px; font-size:12px; color:#8b8b99; }
  .checker { background-image:
      linear-gradient(45deg,#2a2a33 25%,transparent 25%),
      linear-gradient(-45deg,#2a2a33 25%,transparent 25%),
      linear-gradient(45deg,transparent 75%,#2a2a33 75%),
      linear-gradient(-45deg,transparent 75%,#2a2a33 75%);
    background-size:16px 16px; background-position:0 0,0 8px,8px -8px,-8px 0; }
  img { display:block; }
</style></head><body>
  <h1>DEEPER artwork — generated by tools/generate-assets.mjs</h1>
  <div class="row">
    <figure><img src="${icon}" width="256" height="256"><figcaption>icon.png 1024 — iOS, opaque</figcaption></figure>
    <figure><div class="checker"><img src="${adaptive}" width="256" height="256"></div><figcaption>adaptive-icon.png 1024 — transparent</figcaption></figure>
    <figure><div style="background:#0D0D12;padding:10px"><img src="${splash}" width="180" height="180"></div><figcaption>splash-icon.png 512</figcaption></figure>
  </div>

  <h1>Adaptive foreground under OEM masks — the mark must not clip</h1>
  <div class="row">
    <figure>${mask('50%')}<figcaption>circular</figcaption></figure>
    <figure>${mask('38%')}<figcaption>rounded square</figcaption></figure>
    <figure>${mask('0')}<figcaption>full bleed (worst case)</figcaption></figure>
  </div>

  <h1>Legibility at small sizes</h1>
  <div class="row">
    <figure><img src="${icon}" width="120" height="120"><figcaption>120px</figcaption></figure>
    <figure><img src="${icon}" width="76" height="76"><figcaption>76px</figcaption></figure>
    <figure><img src="${icon}" width="48" height="48"><figcaption>48px</figcaption></figure>
    <figure><img src="${favicon}" width="32" height="32"><figcaption>32px</figcaption></figure>
    <figure><img src="${favicon}" width="16" height="16"><figcaption>16px</figcaption></figure>
  </div>
</body></html>`;

fs.writeFileSync(DEST, html);
console.log(`Wrote ${path.relative(ROOT, DEST)} (${(fs.statSync(DEST).size / 1024).toFixed(0)} KiB)`);
